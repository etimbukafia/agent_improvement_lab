def __getattr__(name: str) -> Any:
    """Load comparison helpers without adding optional runner dependencies."""

    if name in {
        "ComparisonError",
        "EnterpriseComparisonRunner",
        "compare_enterprise_metrics",
        "compare_enterprise_reports",
    }:
        from enterprise_agent_improvement_lab import comparison

        return getattr(comparison, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
